@app.route("/", methods=["GET", "POST"])
def home():
    bmi = None
    symptom_result = None
    reply = None

    if request.method == "POST":
        action = request.form.get("action")

        if action == "bmi":
            try:
                weight = float(request.form.get("weight", 0))
                height = float(request.form.get("height", 0))
                if weight > 0 and height > 0:
                    bmi = round(weight / ((height / 100) ** 2), 1)
            except (ValueError, ZeroDivisionError):
                bmi = None

        elif action == "symptom":
            symptom = request.form.get("symptom", "").lower()
            if "fever" in symptom:
                symptom_result = "Fever can have many causes. Rest, drink fluids, and seek medical advice if it persists or worsens."
            elif "cough" in symptom:
                symptom_result = "Cough can have many causes. Rest and fluids may help; seek medical advice if it persists or worsens."
            elif "headache" in symptom:
                symptom_result = "Headaches have many possible causes. Rest and hydration may help; seek medical advice if severe or persistent."
            else:
                symptom_result = "This symptom can have different causes. Please consult a qualified healthcare professional for advice."

        elif action == "chat":
            question = request.form.get("question", "").lower()
            if "water" in question:
                reply = "Water needs vary by person, activity and weather. Drink regularly and follow your clinician's advice."
            elif "sleep" in question:
                reply = "A regular sleep schedule and a calm bedtime routine can support healthy sleep."
            else:
                reply = "I am a demo assistant. For personal symptoms or medical advice, please consult a qualified healthcare professional."

    return render_template_string(
        HTML, bmi=bmi, symptom_result=symptom_result, reply=reply
    )

if __name__ == "__main__":
    app.run(debug=True)
